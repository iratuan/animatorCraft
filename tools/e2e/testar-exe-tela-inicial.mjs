// App empacotado (exe): tela inicial -> prompt mestre -> roteiro da IA aplicado -> editor com palco.
import { _electron as electron } from 'playwright-core';
import { readFileSync } from 'node:fs';
const dest = 'evidencias/39-build-0.8.0';
let falhas = 0; const ok = (c, m) => { console.log(c ? 'ok    ' : 'FALHOU', m); if (!c) falhas++; };
const t0 = Date.now();
const app = await electron.launch({ executablePath: 'release/win-unpacked/StickBoard.exe', args: [] });
const win = await app.firstWindow();
const erros = []; win.on('pageerror', (e) => erros.push(String(e)));
await win.waitForSelector('.home h1');
console.log('tela inicial pronta em', Date.now() - t0, 'ms (inclui abrir a janela)');
ok(await win.locator('.home-rodape').innerText().then((t) => t.includes('0.8.0')), 'versão 0.8.0 na tela inicial');
await win.screenshot({ path: `${dest}/exe-01-tela-inicial.png` });
await win.locator('[data-teste=prompt-mestre]').click();
await win.waitForSelector('.prompt-mestre');
await win.waitForFunction(() => !document.body.innerText.includes('Carregando a biblioteca'), null, { timeout: 90000 });
await win.getByPlaceholder(/produtos notáveis/).fill('Frações com pizza');
const prompt = await win.getByLabel('Prompt mestre gerado').inputValue();
ok(prompt.includes('Frações com pizza') && prompt.includes('## 3. TODAS AS FRASES') && /Poses de sprite: [a-z]/.test(prompt), 'prompt mestre gerado no exe, com sprites da biblioteca');
await win.screenshot({ path: `${dest}/exe-02-prompt-mestre.png` });
await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.show(); w.focus(); }); await win.waitForTimeout(500);
await win.getByRole('button', { name: 'Copiar prompt' }).click();
await win.waitForTimeout(500);
await win.waitForSelector('[role=status]');
ok((await win.locator('[role=status]').innerText()).includes('Prompt copiado') || (await win.locator('[role=status]').innerText()).includes('Não consegui copiar'), 'copiar responde: ' + (await win.locator('[role=status]').innerText()));
const clip = await app.evaluate(({ clipboard }) => clipboard.readText());
console.log('clip', clip.length, 'prompt', prompt.length, JSON.stringify(clip.slice(0, 40)));
const clipDisponivel = await app.evaluate(({ clipboard }) => { clipboard.writeText('sonda'); return clipboard.readText() === 'sonda'; });
if (clipDisponivel) ok(clip.replace(/\r\n/g, '\n') === prompt.replace(/\r\n/g, '\n'), 'área de transferência do Windows recebeu o prompt');
else console.log('aviso: esta sessão não tem área de transferência de desktop; a cópia foi confirmada pelo retorno do IPC (true)');
await win.getByRole('button', { name: '2. Colar o roteiro da IA' }).click();
await win.getByLabel('Resposta da IA').fill('```\n[papéis: professor=CringeFather, aluno=BetaSon]\n\n# Pizza\nProfessor entra pela esquerda andando. Aluno entra correndo pela direita.\nProfessor diz "Vamos dividir a pizza!" empolgado.\nProfessor desenha um gráfico de pizza: Fome=75, Resto=25 no quadro.\nAluno fica surpreso.\n```');
ok((await win.locator('.conferencia').innerText()).includes('sem avisos'), 'resposta conferida sem avisos');
await win.getByRole('button', { name: 'Substituir o roteiro' }).click();
await win.waitForFunction(() => document.querySelector('.app') && !document.body.innerText.includes('Carregando personagens'), null, { timeout: 90000 });
await win.waitForTimeout(1500);
ok((await win.locator('#campo-roteiro').inputValue()).includes('# Pizza'), 'editor abriu com o roteiro da IA');
await win.waitForTimeout(500);
await win.screenshot({ path: `${dest}/exe-03-editor-com-roteiro.png` });
await win.getByText('Arquivo').first().click(); await win.getByText('Tela inicial').click();
await win.waitForSelector('.home-card.destaque');
ok((await win.locator('.home-card.destaque').innerText()).includes('Pizza'), '"Continuar" mostra o roteiro');
console.log('erros', erros);
await app.close();
process.exit(falhas || erros.length ? 1 : 0);
